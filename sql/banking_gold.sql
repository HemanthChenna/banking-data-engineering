
-- BANKING DATA ENGINEERING PROJECT
-- GOLD LAYER

-- =====================================
-- 1. DAILY TRANSACTION SUMMARY
-- =====================================

CREATE OR REPLACE TABLE
BANKING_DEMO.GOLD.DAILY_TRANSACTION_SUMMARY AS

SELECT
    TRY_TO_DATE(
        TRANSACTION_DATE::VARCHAR
    ) AS TRANSACTION_DATE,

    COUNT(*) AS TOTAL_TRANSACTIONS,

    SUM(
        TRY_TO_DECIMAL(AMOUNT::VARCHAR, 18, 2)
    ) AS TOTAL_AMOUNT

FROM BANKING_DEMO.SILVER.TRANSACTIONS

WHERE DATA_QUALITY_STATUS = 'VALID'
  AND TRY_TO_DATE(
      TRANSACTION_DATE::VARCHAR
  ) IS NOT NULL

GROUP BY
    TRY_TO_DATE(TRANSACTION_DATE::VARCHAR);


-- =====================================
-- 2. ACCOUNT TYPE SUMMARY
-- =====================================

CREATE OR REPLACE TABLE
BANKING_DEMO.GOLD.ACCOUNT_TYPE_SUMMARY AS

SELECT
    ACCOUNT_TYPE,

    COUNT(*) AS TOTAL_ACCOUNTS,

    SUM(
        TRY_TO_DECIMAL(BALANCE::VARCHAR, 18, 2)
    ) AS TOTAL_BALANCE,

    AVG(
        TRY_TO_DECIMAL(BALANCE::VARCHAR, 18, 2)
    ) AS AVG_BALANCE

FROM BANKING_DEMO.SILVER.ACCOUNTS

WHERE DATA_QUALITY_STATUS = 'VALID'

GROUP BY ACCOUNT_TYPE;


-- =====================================
-- 3. CUSTOMER CITY SUMMARY
-- =====================================

CREATE OR REPLACE TABLE
BANKING_DEMO.GOLD.CUSTOMER_CITY_SUMMARY AS

SELECT
    CITY,
    COUNT(*) AS TOTAL_CUSTOMERS

FROM BANKING_DEMO.SILVER.CUSTOMERS

WHERE DATA_QUALITY_STATUS = 'VALID'

GROUP BY CITY;


-- =====================================
-- 4. CUSTOMER TRANSACTION SUMMARY
-- =====================================

CREATE OR REPLACE TABLE
BANKING_DEMO.GOLD.CUSTOMER_TRANSACTION_SUMMARY AS

SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    C.CITY,

    COUNT(DISTINCT A.ACCOUNT_ID)
        AS TOTAL_ACCOUNTS,

    COUNT(T.TRANSACTION_ID)
        AS TOTAL_TRANSACTIONS,

    COALESCE(
        SUM(
            TRY_TO_DECIMAL(
                T.AMOUNT::VARCHAR, 18, 2
            )
        ),
        0
    ) AS TOTAL_AMOUNT

FROM BANKING_DEMO.SILVER.CUSTOMERS C

LEFT JOIN BANKING_DEMO.SILVER.ACCOUNTS A
    ON C.CUSTOMER_ID = A.CUSTOMER_ID
    AND A.DATA_QUALITY_STATUS = 'VALID'

LEFT JOIN BANKING_DEMO.SILVER.TRANSACTIONS T
    ON A.ACCOUNT_ID = T.ACCOUNT_ID
    AND T.DATA_QUALITY_STATUS = 'VALID'

WHERE C.DATA_QUALITY_STATUS = 'VALID'

GROUP BY
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    C.CITY;


-- =====================================
-- 5. VERIFY GOLD TABLES
-- =====================================

SELECT *
FROM BANKING_DEMO.GOLD.DAILY_TRANSACTION_SUMMARY;

SELECT *
FROM BANKING_DEMO.GOLD.ACCOUNT_TYPE_SUMMARY;

SELECT *
FROM BANKING_DEMO.GOLD.CUSTOMER_CITY_SUMMARY;

SELECT *
FROM BANKING_DEMO.GOLD.CUSTOMER_TRANSACTION_SUMMARY;


-- =====================================
-- 6. DASHBOARD METRICS
-- =====================================

SELECT
    COUNT(*) AS TOTAL_CUSTOMERS,

    SUM(TOTAL_ACCOUNTS) AS TOTAL_ACCOUNTS,

    SUM(TOTAL_TRANSACTIONS) AS TOTAL_TRANSACTIONS,

    SUM(TOTAL_AMOUNT) AS TOTAL_AMOUNT

FROM BANKING_DEMO.GOLD.CUSTOMER_TRANSACTION_SUMMARY;
