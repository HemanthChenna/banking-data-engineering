
-- BANKING DATA ENGINEERING PROJECT
-- BRONZE LAYER

CREATE DATABASE IF NOT EXISTS BANKING_DEMO;

CREATE SCHEMA IF NOT EXISTS BANKING_DEMO.BRONZE;
CREATE SCHEMA IF NOT EXISTS BANKING_DEMO.SILVER;
CREATE SCHEMA IF NOT EXISTS BANKING_DEMO.GOLD;

CREATE TABLE IF NOT EXISTS BANKING_DEMO.BRONZE.CUSTOMERS (
    CUSTOMER_ID INT,
    CUSTOMER_NAME VARCHAR(200),
    CITY VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS BANKING_DEMO.BRONZE.ACCOUNTS (
    ACCOUNT_ID INT,
    CUSTOMER_ID INT,
    ACCOUNT_TYPE VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS BANKING_DEMO.BRONZE.TRANSACTIONS (
    TRANSACTION_ID INT,
    ACCOUNT_ID INT,
    TRANSACTION_DATE DATE,
    AMOUNT NUMBER(18,2)
);
